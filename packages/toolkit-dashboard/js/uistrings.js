function translateProfileEntry(category, value) {
    const lng = (localStorage.getItem('qf-lang') || 'EN').toUpperCase();
    const dict = profileEntryStrings[category] && profileEntryStrings[category][lng];
    return (dict && dict[value]) || value;
}

